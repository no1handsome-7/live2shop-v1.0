BEGIN;

CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    status TEXT NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'DISABLED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE anchors (
    anchor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'DISABLED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE items (
    item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    title TEXT NOT NULL,

    category_id BIGINT,
    category_path TEXT[] NOT NULL DEFAULT '{}',

    brand TEXT,
    style_tags TEXT[] NOT NULL DEFAULT '{}',
    attributes JSONB NOT NULL DEFAULT '{}'::jsonb,

    price_cent BIGINT NOT NULL CHECK (price_cent >= 0),
    currency CHAR(3) NOT NULL DEFAULT 'CNY',

    inventory BIGINT NOT NULL DEFAULT 0 CHECK (inventory >= 0),

    image_uri TEXT,
    popularity_score REAL NOT NULL DEFAULT 0,

    status TEXT NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'OFF_SHELF', 'SOLD_OUT')),

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_items_category_id ON items(category_id);
CREATE INDEX idx_items_brand ON items(brand);
CREATE INDEX idx_items_status ON items(status);
CREATE INDEX idx_items_style_tags_gin ON items USING GIN(style_tags);
CREATE INDEX idx_items_attributes_gin ON items USING GIN(attributes);

COMMIT;
