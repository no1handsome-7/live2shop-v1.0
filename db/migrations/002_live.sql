BEGIN;

CREATE TABLE live_rooms (
    room_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    anchor_id BIGINT NOT NULL
        REFERENCES anchors(anchor_id),

    title TEXT NOT NULL,

    status TEXT NOT NULL DEFAULT 'OFFLINE'
        CHECK (status IN ('OFFLINE', 'LIVE', 'ENDED')),

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE live_stream_sessions (
    stream_session_id UUID PRIMARY KEY,

    room_id BIGINT NOT NULL
        REFERENCES live_rooms(room_id),

    ingest_protocol TEXT NOT NULL,

    status TEXT NOT NULL
        CHECK (status IN ('LIVE', 'ENDED', 'FAILED')),

    started_at TIMESTAMPTZ NOT NULL,
    ended_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CHECK (ended_at IS NULL OR ended_at >= started_at)
);

CREATE INDEX idx_stream_sessions_room_started
ON live_stream_sessions(room_id, started_at DESC);

CREATE TABLE room_items (
    room_id BIGINT NOT NULL
        REFERENCES live_rooms(room_id),

    item_id BIGINT NOT NULL
        REFERENCES items(item_id),

    sort_order INTEGER NOT NULL DEFAULT 0,

    active_from TIMESTAMPTZ,
    active_until TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    PRIMARY KEY(room_id, item_id),

    CHECK (
        active_until IS NULL
        OR active_from IS NULL
        OR active_until >= active_from
    )
);

CREATE INDEX idx_room_items_room_order
ON room_items(room_id, sort_order);

CREATE TABLE live_segments (
    segment_id UUID PRIMARY KEY,

    stream_session_id UUID NOT NULL
        REFERENCES live_stream_sessions(stream_session_id),

    room_id BIGINT NOT NULL
        REFERENCES live_rooms(room_id),

    seq_no BIGINT NOT NULL CHECK (seq_no >= 0),

    start_pts_ms BIGINT NOT NULL CHECK (start_pts_ms >= 0),
    end_pts_ms BIGINT NOT NULL CHECK (end_pts_ms > start_pts_ms),

    object_uri TEXT NOT NULL,
    sha256_hex TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    UNIQUE(stream_session_id, seq_no)
);

CREATE INDEX idx_segments_stream_pts
ON live_segments(stream_session_id, start_pts_ms, end_pts_ms);

CREATE TABLE content_states (
    state_id UUID PRIMARY KEY,

    segment_id UUID NOT NULL
        REFERENCES live_segments(segment_id),

    room_id BIGINT NOT NULL
        REFERENCES live_rooms(room_id),

    stream_session_id UUID NOT NULL
        REFERENCES live_stream_sessions(stream_session_id),

    start_pts_ms BIGINT NOT NULL CHECK (start_pts_ms >= 0),
    end_pts_ms BIGINT NOT NULL CHECK (end_pts_ms > start_pts_ms),

    product_visible BOOLEAN NOT NULL DEFAULT FALSE,

    active_item_id BIGINT
        REFERENCES items(item_id),

    category_id BIGINT,
    category_path TEXT[] NOT NULL DEFAULT '{}',

    brand TEXT,
    style_tags TEXT[] NOT NULL DEFAULT '{}',
    attributes JSONB NOT NULL DEFAULT '{}'::jsonb,

    price_cent BIGINT CHECK (price_cent IS NULL OR price_cent >= 0),
    promotion_tags TEXT[] NOT NULL DEFAULT '{}',

    transition TEXT NOT NULL,

    catalog_candidates JSONB NOT NULL DEFAULT '[]'::jsonb,
    evidence JSONB NOT NULL DEFAULT '[]'::jsonb,

    confidence REAL NOT NULL
        CHECK (confidence >= 0 AND confidence <= 1),

    model_name TEXT NOT NULL,
    model_version TEXT NOT NULL,
    model_alias TEXT,

    embedding_version TEXT NOT NULL,

    previous_state_id UUID,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    UNIQUE(segment_id, model_name, model_version)
);

CREATE INDEX idx_content_states_stream_pts
ON content_states(stream_session_id, start_pts_ms, end_pts_ms);

CREATE INDEX idx_content_states_item
ON content_states(active_item_id);

CREATE INDEX idx_content_states_model
ON content_states(model_name, model_version);

CREATE INDEX idx_content_states_style_tags_gin
ON content_states USING GIN(style_tags);

COMMIT;
